const GLYPHS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split('|')]));
const SPACE = 3;
export const FONT_HEIGHT = 7;

const normalize = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[•·]/g, '-').toUpperCase();

/** Width in px of `text` drawn at `scale` (each font dot is scale × scale px). */
export function textWidth(text, scale = 1) {
    let w = 0;
    for (const ch of normalize(text)) w += ((GLYPHS[ch] ? GLYPHS[ch][0].length : SPACE) + 1) * scale;
    return Math.max(0, w - scale);
}

/** Draws `text` into an RGBA buffer `width` px wide; (x, y) is the top left corner. */
export function drawText(rgba, width, text, x, y, color, scale = 1) {
    const height = rgba.length / 4 / width;
    for (const ch of normalize(text)) {
        const g = GLYPHS[ch];
        if (!g) { x += (SPACE + 1) * scale; continue; }
        g.forEach((row, r) => [...row].forEach((bit, c) => {
            if (bit !== '#') return;
            for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
                const px = x + c * scale + dx, py = y + r * scale + dy;
                if (px < 0 || py < 0 || px >= width || py >= height) continue;
                rgba.set(color, (py * width + px) * 4);
            }
        }));
        x += (g[0].length + 1) * scale;
    }
}
